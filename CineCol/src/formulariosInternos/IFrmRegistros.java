    public void llenarCombo() {
        try (Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUsername(), conexion.getPassword())) {
            comboGenero.removeAllItems();
            comboGenero.addItem("Seleccione...");
            lista.clear();

            Statement stm = con.createStatement();
            String query = "call MostrarGeneros();";
            ResultSet rs = stm.executeQuery(query);

            while (rs.next()) {
                String genero = rs.getString("nombre_gen");
                int id = rs.getInt("id_genero");
                lista.add(new Generos(id, genero));
                comboGenero.addItem(genero);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    
    public void guardar(){
        if (!txtNombrePelicula.getText().isEmpty() && comboGenero.getSelectedIndex() > 0 
                && !txtDirector.getText().isEmpty() && sldDuracion.getValue() > 0) {
            try (Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUsername(), conexion.getPassword())) {
                String nombre = txtNombrePelicula.getText().toUpperCase();
                int posCombo = comboGenero.getSelectedIndex() - 1;
                int genero = lista.get(posCombo).getId();
                Date anio = dtcAnio.getDate();
                String director = txtDirector.getText().toUpperCase();
                int duracionMin = sldDuracion.getValue();
                if (anio == null) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Selecciona la fecha de estreno");
                    return;
                }
                java.sql.Date fechaSql = new java.sql.Date(anio.getTime());
                
                PreparedStatement pstm = con.prepareCall("call GuardarPeliculas(?,?,?,?,?)");
                pstm.setString(1, nombre);
                pstm.setString(2, director);
                pstm.setInt(3, duracionMin);
                pstm.setDate(4, fechaSql);
                pstm.setInt(5, genero);
                pstm.executeQuery();
                
                JOptionPane.showMessageDialog(rootPane, "Guardado con exito");

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(rootPane, e.toString());
            }
        }
    }
    
    
