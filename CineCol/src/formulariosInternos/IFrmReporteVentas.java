    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        java.util.Date desde = dtcAnio1.getDate();
        java.util.Date hasta = dtcAnio2.getDate();

        // Que ambas fechas estén seleccionadas
        if (desde == null || hasta == null) {
            JOptionPane.showMessageDialog(this, "Selecciona las dos fechas");
            return;
        }

        // Que el rango sea válido
        if (desde.after(hasta)) {
            JOptionPane.showMessageDialog(this,
                "La fecha inicial no puede ser mayor que la final");
            return;
        }

        buscarPorFechas(new java.sql.Date(desde.getTime()),
                        new java.sql.Date(hasta.getTime()));
    }//GEN-LAST:event_btnBuscarActionPerformed


