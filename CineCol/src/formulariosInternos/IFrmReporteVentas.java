    private void buscarPorFechas(java.sql.Date desde, java.sql.Date hasta) {
        try (Connection conexion = DriverManager.getConnection(
                con.getUrl(), con.getUsername(), con.getPassword());
            CallableStatement cs = conexion.prepareCall("{call ReporteVentas(?, ?)}")) {

            cs.setDate(1, desde);
            cs.setDate(2, hasta);

            try (ResultSet rs = cs.executeQuery()) {
                DefaultTableModel modelo = new DefaultTableModel();
                ResultSetMetaData rsmt = rs.getMetaData();
                int columnas = rsmt.getColumnCount();

                for (int i = 1; i <= columnas; i++) {
                    modelo.addColumn(rsmt.getColumnLabel(i));
                }
                while (rs.next()) {
                    Object[] fila = new Object[columnas];
                    for (int i = 1; i <= columnas; i++) {
                        fila[i - 1] = rs.getObject(i);
                    }
                    modelo.addRow(fila);
                }
                tableReporte.setModel(modelo);

                if (modelo.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(this, "No hay ventas en ese rango de fechas");
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }

