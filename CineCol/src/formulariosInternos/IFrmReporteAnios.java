    private void buscarPorFechas(java.sql.Date desde, java.sql.Date hasta) {
    try (Connection con = DriverManager.getConnection(
            conexion.getUrl(), conexion.getUsername(), conexion.getPassword());
         CallableStatement cs = con.prepareCall("{call BuscarPeliculasPorFecha(?, ?)}")) {

        cs.setDate(1, desde);
        cs.setDate(2, hasta);

        try (ResultSet rs = cs.executeQuery()) {
            DefaultTableModel modelo = new DefaultTableModel();
            ResultSetMetaData rsmt = rs.getMetaData();

            for (int i = 1; i <= rsmt.getColumnCount(); i++) {
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            while(rs.next()){
                String nombre_pelicula = rs.getString("Nombre Pelicula");
                String nombre_gen = rs.getString("Genero");
                String director = rs.getString("Director");
                int duracion = rs.getInt("Duracion (minutos)"); 
                String fecha_estreno = rs.getString("Fecha Estreno");
                
                Object[] filas = new Object[rsmt.getColumnCount()];
                for(int i = 1; i<=rsmt.getColumnCount(); i++){
                    filas[i-1]= rs.getObject(i);
                }
                modelo.addRow(filas);
            }
            tableReporte.setModel(modelo);

            if (modelo.getRowCount() == 0) {
                JOptionPane.showMessageDialog(this,
                    "No hay películas en ese rango de fechas");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(rootPane, e.toString());
    }
}

