    public void llenarCombo() {
        try (Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUsername(), conexion.getPassword())) {
            comboGenero.removeAllItems();
            comboGenero.addItem("Seleccione...");
            lista.clear();
            
            Statement stm = con.createStatement();
            String query = "call MostrarGeneros();";
            ResultSet rs = stm.executeQuery(query);

            while (rs.next()) {
                String genero = rs.getString("nombre_gen");
                int id = rs.getInt("id_genero");
                lista.add(new Generos(id, genero));
                comboGenero.addItem(genero);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    
    public void mostrarInfo(){
        if (comboGenero.getSelectedIndex() > 0){
            try (Connection con = DriverManager.getConnection(conexion.getUrl(), conexion.getUsername(), conexion.getPassword())) {
                DefaultTableModel modelo = new DefaultTableModel();
                PreparedStatement pstm = con.prepareCall("call mostrarPeliGenero(?)");
                int posCombo = comboGenero.getSelectedIndex() - 1;
                int genero = lista.get(posCombo).getId();
                pstm.setInt(1, genero);
                ResultSet rs = pstm.executeQuery();
                ResultSetMetaData rsmt = rs.getMetaData();
                for(int i =1; i<= rsmt.getColumnCount(); i++){
                    modelo.addColumn(rsmt.getColumnLabel(i));
                }
                while(rs.next()){
                    String nombre_pelicula = rs.getString("Nombre Pelicula");
                    String director = rs.getString("Director");
                    int duracion = rs.getInt("Duracion (minutos)"); 
                    String fecha_estreno = rs.getString("Fecha Estreno");

                    Object[] filas = new Object[rsmt.getColumnCount()];
                    for(int i = 1; i<=rsmt.getColumnCount(); i++){
                        filas[i-1]= rs.getObject(i);
                    }
                    modelo.addRow(filas);
                }
                tableReporte.setModel(modelo);
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(rootPane, e.toString());
            }
        }
    }

