    // Llena un combo con el id (columna 1) y el texto (columna 2)
    private void cargarCombo(String llamada,
                             javax.swing.JComboBox<Opcion> combo) {
        try (Connection conexion = DriverManager.getConnection(
                con.getUrl(), con.getUsername(), con.getPassword());
             CallableStatement cs = conexion.prepareCall(llamada);
             ResultSet rs = cs.executeQuery()) {

            combo.removeAllItems();
            while (rs.next()) {
                combo.addItem(new Opcion(rs.getInt(1), rs.getString(2)));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }

    private void guardarFuncion() {
        Opcion pelicula = (Opcion) comboPeliculas.getSelectedItem();
        Opcion sala = (Opcion) comboSalas.getSelectedItem();

        if (pelicula == null || sala == null) {
            JOptionPane.showMessageDialog(this,
                    "Debe haber al menos una película y una sala registradas");
            return;
        }
        if (dtcFecha.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Selecciona la fecha");
            return;
        }

        BigDecimal precio;
        try {
            precio = new BigDecimal(txtPrecio.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Escribe el precio solo con números, por ejemplo 12000");
            return;
        }
        if (precio.signum() <= 0) {
            JOptionPane.showMessageDialog(this,
                    "El precio debe ser mayor que cero");
            return;
        }

        // Juntar la fecha del calendario con la hora del spinner
        Calendar dia = Calendar.getInstance();
        dia.setTime(dtcFecha.getDate());
        Calendar hora = Calendar.getInstance();
        hora.setTime((java.util.Date) spinHora.getValue());
        dia.set(Calendar.HOUR_OF_DAY, hora.get(Calendar.HOUR_OF_DAY));
        dia.set(Calendar.MINUTE, hora.get(Calendar.MINUTE));
        dia.set(Calendar.SECOND, 0);
        dia.set(Calendar.MILLISECOND, 0);
        Timestamp fechaHora = new Timestamp(dia.getTimeInMillis());

        try (Connection conexion = DriverManager.getConnection(
                con.getUrl(), con.getUsername(), con.getPassword());
             CallableStatement cs = conexion.prepareCall("{call GuardarFuncion(?,?,?,?)}")) {

            cs.setInt(1, pelicula.getId());
            cs.setInt(2, sala.getId());
            cs.setTimestamp(3, fechaHora);
            cs.setBigDecimal(4, precio);
            cs.executeUpdate();

            JOptionPane.showMessageDialog(this, "Función registrada con éxito");
            txtPrecio.setText("");
            dtcFecha.setDate(null);

        } catch (SQLException e) {
            if ("45000".equals(e.getSQLState())) {
                JOptionPane.showMessageDialog(this, e.getMessage());
            } else {
                JOptionPane.showMessageDialog(rootPane, e.toString());
            }
        }
    }
    
